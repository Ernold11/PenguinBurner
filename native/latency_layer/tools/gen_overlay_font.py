def _row_to_bits(row: str) -> int:
    bits = 0
    for col in range(WIDTH):
        ch = row[col] if col < len(row) else "."
        if ch not in (".", " "):
            bits |= 1 << (WIDTH - 1 - col)
    return bits


def _validate() -> None:
    for ch, rows in GLYPHS.items():
        if len(rows) != HEIGHT:
            raise SystemExit(f"glyph {ch!r}: {len(rows)} rows, expected {HEIGHT}")
        for i, row in enumerate(rows):
            if len(row) != WIDTH:
                raise SystemExit(
                    f"glyph {ch!r} row {i}: width {len(row)}, expected {WIDTH}"
                )


def preview() -> None:
    for ch, rows in GLYPHS.items():
        print(f"=== {ch!r} ===")
        for row in rows:
            print("".join("#" if c not in (".", " ") else "." for c in row))
        print()


def emit_cpp() -> None:
    print("std::array<uint16_t, 14> overlay_glyph_rows(char ch) {")
    print(
        "    switch (static_cast<char>("
        "std::toupper(static_cast<unsigned char>(ch)))) {"
    )
    for ch, rows in GLYPHS.items():
        literal = ", ".join(f"0x{_row_to_bits(r):03x}" for r in rows)
        case = "'\\''" if ch == "'" else f"'{ch}'"
        print(f"        case {case}: return {{{literal}}};")
    zeros = ", ".join(["0x000"] * HEIGHT)
    print(f"        default: return {{{zeros}}};")
    print("    }")
    print("}")


if __name__ == "__main__":
    _validate()
    if "--cpp" in sys.argv:
        emit_cpp()
    else:
        preview()
